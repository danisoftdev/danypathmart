<?php

declare(strict_types=1);

require __DIR__ . '/../vendor/autoload.php';

spl_autoload_register(static function (string $class): void {
    $prefix = 'App\\';
    if (!str_starts_with($class, $prefix)) {
        return;
    }
    $relative = substr($class, strlen($prefix));
    $parts = explode('\\', $relative);
    $dir = strtolower(array_shift($parts));
    $path = __DIR__ . '/../' . $dir . '/' . implode('/', $parts) . '.php';
    if (is_file($path)) {
        require $path;
    }
});

use App\Config\Database;
use App\Helpers\FinancialReport;

$pdo = Database::pdo();
$pdo->query('SELECT cost_price FROM products LIMIT 1');
$report = FinancialReport::build($pdo);
echo 'OK net_interest=' . $report['interest']['net_interest'] . PHP_EOL;
